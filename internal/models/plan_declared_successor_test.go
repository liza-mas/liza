// D-167: a selected-child slot follows a unique same-pair plan-declared
// replacement: the correcting plan's output names the child in supersedes and
// generated the successor. Splits and anything not provably that child stay
// permanent retirements, so the slot keeps naming the retired child.

const (
	declaredSlot   = "provider-cp-0"
	slotTransition = "architecture-to-code-plan"
)

func slotResolver(t *testing.T) *pipeline.Resolver {
	t.Helper()
	cfg, err := pipeline.LoadFromBytes(embedded.PipelineConfigContent())
	if err != nil {
		t.Fatal(err)
	}
	return pipeline.NewResolver(cfg)
}

// mergedSlotPlan is a MERGED architecture plan whose hand-off ran, with one
// output per supersedes value ("" for an ordinary output).
func mergedSlotPlan(id string, supersedes ...string) models.Task {
	plan := models.Task{ID: id, RolePair: "architecture-pair", Status: models.TaskStatusMerged,
		TransitionsExecuted: map[string]bool{slotTransition: true}}
	for _, original := range supersedes {
		plan.Output = append(plan.Output, models.OutputEntry{Desc: "plan", Supersedes: original})
	}
	return plan
}

// planSuccessor is a code plan generated by plan, replacing original.
func planSuccessor(id, plan, original string) models.Task {
	task := slotChild(id, models.TaskStatusDraftCodingPlan)
	task.ParentTasks = []string{plan}
	task.Supersedes = &original
	return task
}

// correctedSlot is the B-402 shape: provider's output 0 generated
// provider-cp-0, which the correcting plan fix replaced with fix-cp-0.
func correctedSlot() []models.Task {
	return []models.Task{
		mergedSlotPlan("provider", ""),
		slotChild(declaredSlot, models.TaskStatusSuperseded, "fix-cp-0"),
		mergedSlotPlan("fix", declaredSlot),
		planSuccessor("fix-cp-0", "fix", declaredSlot),
	}
}

func withTask(tasks []models.Task, id string, edit func(*models.Task)) []models.Task {
	tasks = slices.Clone(tasks)
	for i := range tasks {
		if tasks[i].ID == id {
			edit(&tasks[i])
		}
	}
	return tasks
}

func slotDependency() models.ProviderDependency {
	return models.ProviderDependency{ProviderTask: "provider", Transition: slotTransition, Outputs: []int{0}}
}

func TestEffectiveProviderChildrenFollowsPlanDeclaredSuccessor_D167(t *testing.T) {
	t.Parallel()
	resolver := slotResolver(t)
	without := func(tasks []models.Task, id string) []models.Task {
		return slices.DeleteFunc(slices.Clone(tasks), func(task models.Task) bool { return task.ID == id })
	}
	for name, tc := range map[string]struct {
		tasks []models.Task
		want  string
	}{
		"unique plan-declared successor": {tasks: correctedSlot(), want: "fix-cp-0"},
		"split across two outputs": {tasks: append(withTask(correctedSlot(), declaredSlot, func(task *models.Task) {
			task.SupersededBy = []string{"fix-cp-0", "fix-cp-1"}
		}), planSuccessor("fix-cp-1", "fix", declaredSlot)), want: declaredSlot},
		"successor without supersedes back-link": {tasks: withTask(correctedSlot(), "fix-cp-0", func(task *models.Task) {
			task.Supersedes = nil
		}), want: declaredSlot},
		"successor in another role pair": {tasks: withTask(correctedSlot(), "fix-cp-0", func(task *models.Task) {
			task.RolePair = "coding-pair"
		}), want: declaredSlot},
		"plan output does not name the child": {tasks: withTask(correctedSlot(), "fix", func(task *models.Task) {
			task.Output[0].Supersedes = ""
		}), want: declaredSlot},
		"plan names the child in two outputs": {tasks: withTask(correctedSlot(), "fix", func(task *models.Task) {
			task.Output = append(task.Output, models.OutputEntry{Desc: "plan", Supersedes: declaredSlot})
		}), want: declaredSlot},
		"missing plan":      {tasks: without(correctedSlot(), "fix"), want: declaredSlot},
		"missing successor": {tasks: without(correctedSlot(), "fix-cp-0"), want: declaredSlot},
		"plan transition not executed": {tasks: withTask(correctedSlot(), "fix", func(task *models.Task) {
			task.TransitionsExecuted = nil
		}), want: declaredSlot},
		"successor parented by the provider": {tasks: withTask(correctedSlot(), "fix-cp-0", func(task *models.Task) {
			task.ParentTasks = []string{"provider"}
		}), want: declaredSlot},
		// A same-pair task under the plan with the reciprocal link is not
		// enough: it must be the child the declaring output generated.
		"successor is not the declaring output's child": {tasks: append(withTask(without(correctedSlot(), "fix-cp-0"), declaredSlot, func(task *models.Task) {
			task.SupersededBy = []string{"fix-other"}
		}), planSuccessor("fix-other", "fix", declaredSlot)), want: declaredSlot},
		"successor of the declaring output at another index": {tasks: append(withTask(without(correctedSlot(), "fix-cp-0"), "fix", func(task *models.Task) {
			task.Output = []models.OutputEntry{{Desc: "plan"}, {Desc: "plan", Supersedes: declaredSlot}}
		}), planSuccessor("fix-cp-0", "fix", declaredSlot)), want: declaredSlot},
		"plan then same-pair replace-task": {tasks: append(withTask(correctedSlot(), "fix-cp-0", func(task *models.Task) {
			*task = replacedBy(*task, "fix-cp-0-r1", true)
			task.Status = models.TaskStatusSuperseded
			task.SupersededBy = []string{"fix-cp-0-r1"}
		}), func() models.Task {
			task := slotChild("fix-cp-0-r1", models.TaskStatusDraftCodingPlan)
			task.ParentTasks = []string{"fix"}
			return task
		}()), want: "fix-cp-0-r1"},
		"replan then plan": {tasks: []models.Task{
			mergedSlotPlan("provider", ""),
			replannedChild(declaredSlot),
			replanOf(slotChild("provider-cp-0-replan-1", models.TaskStatusSuperseded, "fix-cp-0"), declaredSlot),
			mergedSlotPlan("fix", "provider-cp-0-replan-1"),
			planSuccessor("fix-cp-0", "fix", "provider-cp-0-replan-1"),
		}, want: "fix-cp-0"},
		"cycle": {tasks: []models.Task{
			mergedSlotPlan("provider", "fix-cp-0"),
			replanOf(slotChild(declaredSlot, models.TaskStatusSuperseded, "fix-cp-0"), "fix-cp-0"),
			mergedSlotPlan("fix", declaredSlot),
			func() models.Task {
				task := planSuccessor("fix-cp-0", "fix", declaredSlot)
				task.Status = models.TaskStatusSuperseded
				task.SupersededBy = []string{declaredSlot}
				return task
			}(),
		}, want: declaredSlot},
	} {
		t.Run(name, func(t *testing.T) {
			t.Parallel()
			// GIVEN a consumer selecting the provider's output 0
			state := &models.State{Tasks: tc.tasks}

			// WHEN the selection is resolved
			_, children, err := models.EffectiveProviderChildren(slotDependency(), state, resolver)

			// THEN the slot names the expected task
			if err != nil {
				t.Fatal(err)
			}
			if len(children) != 1 || children[0] != tc.want {
				t.Fatalf("slot resolves to %v, want [%s]", children, tc.want)
			}
		})
	}
}

// Guard: provider aliasing (reservations) and the replan/replace-task walks
// keep their meaning; only selected-child slots follow a plan replacement.
func TestGenericLineageIgnoresPlanDeclaredSuccessor_D167(t *testing.T) {
	t.Parallel()
	state := &models.State{Tasks: correctedSlot()}
	if successor, ok := models.ProviderChildSuccessor(state, declaredSlot); ok {
		t.Fatalf("ProviderChildSuccessor followed a plan-declared successor to %s", successor.ID)
	}
	if successor, ok := models.ReplanSuccessor(state, declaredSlot); ok {
		t.Fatalf("ReplanSuccessor followed a plan-declared successor to %s", successor.ID)
	}
	if got := models.EffectiveReservationProvider(state, declaredSlot); got != declaredSlot {
		t.Fatalf("EffectiveReservationProvider(%s) = %s, want it unchanged", declaredSlot, got)
	}
}

func TestProviderDependencyOnPlanDeclaredSuccessor_D167(t *testing.T) {
	t.Parallel()
	resolver := slotResolver(t)
	consumer := models.Task{ID: "consumer", RolePair: "code-planning-pair", Status: models.TaskStatusDraftCodingPlan,
		ProviderDependencies: []models.ProviderDependency{slotDependency()}}
	unmet := func(tasks []models.Task) []models.DependencySatisfaction {
		return models.UnmetProviderDependencies(&consumer, append(slices.Clone(tasks), consumer), resolver)
	}

	t.Run("waits for the successor", func(t *testing.T) {
		t.Parallel()
		got := unmet(correctedSlot())
		if len(got) != 1 || got[0].Kind != models.DependencyUnsatisfiedPending || !slices.Equal(got[0].BlockingIDs, []string{"fix-cp-0"}) {
			t.Fatalf("readiness = %+v, want pending on fix-cp-0", got)
		}
	})
	t.Run("satisfied once the successor merged", func(t *testing.T) {
		t.Parallel()
		if got := unmet(withTask(correctedSlot(), "fix-cp-0", func(task *models.Task) { task.Status = models.TaskStatusMerged })); len(got) != 0 {
			t.Fatalf("readiness = %+v, want satisfied", got)
		}
	})
	t.Run("held provider still gates", func(t *testing.T) {
		t.Parallel()
		got := unmet(withTask(correctedSlot(), "provider", func(task *models.Task) {
			task.PlanCheck = &models.PlanCheck{Verdict: models.PlanCheckHeld}
		}))
		if len(got) != 1 || got[0].Kind != models.DependencyUnsatisfiedPending || !slices.Equal(got[0].BlockingIDs, []string{"provider"}) {
			t.Fatalf("readiness = %+v, want pending on the held provider", got)
		}
	})
	t.Run("unexecuted provider transition still gates", func(t *testing.T) {
		t.Parallel()
		got := unmet(withTask(correctedSlot(), "provider", func(task *models.Task) { task.TransitionsExecuted = nil }))
		if len(got) != 1 || got[0].Kind != models.DependencyUnsatisfiedPending || !slices.Equal(got[0].BlockingIDs, []string{"provider"}) {
			t.Fatalf("readiness = %+v, want pending on the provider transition", got)
		}
	})
	t.Run("foreign child at the projected ID is still refused", func(t *testing.T) {
		t.Parallel()
		got := unmet(withTask(correctedSlot(), declaredSlot, func(task *models.Task) {
			task.Status = models.TaskStatusDraftCodingPlan
			task.SupersededBy = nil
			task.ParentTasks = []string{"fix"}
		}))
		if len(got) != 1 || !got[0].Invalid() {
			t.Fatalf("readiness = %+v, want the foreign child refused", got)
		}
	})
	// A successor continues the provider's slot only: correcting a task the
	// provider did not generate, whose ID collides with the projection, does
	// not establish the slot's origin, even once the successor merged.
	foreignOriginal := func(tasks []models.Task) []models.Task {
		return append(withTask(tasks, declaredSlot, func(task *models.Task) {
			task.ParentTasks = []string{"unrelated-plan"}
		}), consumer)
	}
	for name, laundered := range map[string]struct {
		successor string
		tasks     []models.Task
	}{
		"correcting plan's successor": {successor: "fix-cp-0", tasks: foreignOriginal(correctedSlot())},
		// The successor's parent being the provider must not skip the check.
		"successor under the provider itself": {successor: "provider-cp-1", tasks: foreignOriginal(append(withTask(withTask(correctedSlot(), "provider", func(task *models.Task) {
			task.Output = append(task.Output, models.OutputEntry{Desc: "plan", Supersedes: declaredSlot})
		}), declaredSlot, func(task *models.Task) {
			task.SupersededBy = []string{"provider-cp-1"}
		}), planSuccessor("provider-cp-1", "provider", declaredSlot)))},
	} {
		t.Run("retired foreign original is not laundered by the "+name, func(t *testing.T) {
			t.Parallel()
			tasks := withTask(laundered.tasks, laundered.successor, func(task *models.Task) { task.Status = models.TaskStatusMerged })
			got := models.UnmetProviderDependencies(&consumer, tasks, resolver)
			if len(got) != 1 || !got[0].Invalid() || !strings.Contains(got[0].Reason, "wrong role or provenance") {
				t.Fatalf("readiness = %+v, want the successor of a foreign original refused", got)
			}
		})
		t.Run("state validation refuses a foreign original laundered by the "+name, func(t *testing.T) {
			t.Parallel()
			err := statevalidate.ValidateProviderDependencies(&models.State{Tasks: laundered.tasks}, resolver)
			if err == nil || !strings.Contains(err.Error(), "child "+laundered.successor+" has incorrect provider provenance") {
				t.Fatalf("validation = %v, want the successor's provenance refused", err)
			}
		})
	}
}
